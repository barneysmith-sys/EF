export const Q_BASE_YEAR = 2026;
export const Q_SPAN = 20; // 2026 Q1 → 2030 Q4

export function qIndex(year: number, quarter: number) {
  return (year - Q_BASE_YEAR) * 4 + (quarter - 1);
}

export function qLabel(i: number) {
  const year = Q_BASE_YEAR + Math.floor(i / 4);
  return `Q${(i % 4) + 1} ${year}`;
}

